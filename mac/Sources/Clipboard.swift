import AppKit
import CryptoKit

/// Universal clipboard: text and images, both ways. The pasteboard has no change notification, so it polls
/// `changeCount` (a cheap integer read) twice a second.
final class ClipboardSync {
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var lastDigest: Data?
    private var timer: Timer?
    // Password managers mark secrets with these types (nspasteboard.org); never send them.
    private let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "gif", "webp", "tiff", "tif", "bmp"]

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.2 // lets macOS coalesce wake-ups
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func digest(_ kind: Kind, _ data: Data) -> Data {
        var hasher = SHA256()
        hasher.update(data: Data([kind.rawValue]))
        hasher.update(data: data)
        return Data(hasher.finalize())
    }

    func apply(_ kind: Kind, _ payload: Data) {
        guard Prefs.syncClipboard else { return }
        let incoming = digest(kind, payload)
        if incoming == lastDigest { return }
        switch kind {
        case .text:
            pasteboard.clearContents()
            pasteboard.setString(String(decoding: payload, as: UTF8.self), forType: .string)
        case .image:
            guard let rep = NSBitmapImageRep(data: payload) else { log("received an image macOS cannot read; ignored"); return }
            pasteboard.clearContents()
            if let png = rep.representation(using: .png, properties: [:]) { pasteboard.setData(png, forType: .png) }
            if let tiff = rep.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
        default: return
        }
        lastDigest = incoming
        lastChangeCount = pasteboard.changeCount
        log("\(link.phoneName) -> Mac: clipboard \(kind) (\(payload.count) bytes)")
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard Prefs.syncClipboard, link.connected else { return }
        let types = pasteboard.types ?? []
        if !privateTypes.isDisjoint(with: types) { return }
        guard let (kind, payload) = read(types), payload.count < maxFrame - 64 else { return }
        let outgoing = digest(kind, payload)
        guard outgoing != lastDigest else { return }
        lastDigest = outgoing
        link.sendToPhone(kind, payload)
        log("Mac -> \(link.phoneName): clipboard \(kind) (\(payload.count) bytes)")
    }

    /// A URL on the clipboard, if that is all it holds.
    func copiedURL() -> URL? {
        guard let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.contains(" "), let url = URL(string: text), ["http", "https"].contains(url.scheme ?? "") else { return nil }
        return url
    }

    private func read(_ types: [NSPasteboard.PasteboardType]) -> (Kind, Data)? {
        // A copied file in Finder: send it only if it is a single image (use Send Files for anything else).
        if types.contains(.fileURL) {
            let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            if urls.count == 1, let url = urls.first, imageExtensions.contains(url.pathExtension.lowercased()),
               let data = try? Data(contentsOf: url) {
                return (.image, phoneFriendlyImage(data))
            }
            return nil
        }
        // Text wins when present: apps such as Word also attach a picture of copied text.
        if let text = pasteboard.string(forType: .string), !text.isEmpty { return (.text, Data(text.utf8)) }
        if let png = pasteboard.data(forType: .png) { return (.image, png) }
        if let tiff = pasteboard.data(forType: .tiff) { return (.image, phoneFriendlyImage(tiff)) }
        return nil
    }

    // Keep PNG and JPEG as they are; convert anything else (TIFF, HEIC...) to PNG.
    private func phoneFriendlyImage(_ data: Data) -> Data {
        let bytes = [UInt8](data.prefix(4))
        if bytes.starts(with: [0x89, 0x50, 0x4E, 0x47]) || bytes.starts(with: [0xFF, 0xD8]) { return data }
        guard let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) else { return data }
        return png
    }
}
